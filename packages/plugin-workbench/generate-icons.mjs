// Generate the vanilla frontend masks from the launcher's locked Lucide package.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const require = createRequire(new URL('../../apps/desktop/package.json', import.meta.url));
const packageFile = require.resolve('@lucide/vue/package.json');
const packageRoot = path.dirname(packageFile);
const metadata = JSON.parse(readFileSync(packageFile, 'utf8'));
if (metadata.version !== '1.61.0') throw new Error('Review Lucide version/license before regenerating plugin icons.');
const icons = {
    refresh: 'refresh-cw', file: 'file-text', folder: 'folder', search: 'search', check: 'check', copy: 'copy',
    save: 'save', export: 'download', plus: 'plus', close: 'x', trash: 'trash', map: 'map', pin: 'map-pin',
    graph: 'network', layers: 'layers', tool: 'hammer', clock: 'clock', shield: 'shield-check',
    settings: 'sliders-horizontal', send: 'send', text: 'type', box: 'box',
};
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
function node([tag, attributes, children = []]) {
    return `<${tag} ${Object.entries(attributes).filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${escape(value)}"`).join(' ')}>${children.map(node).join('')}</${tag}>`;
}
const license = readFileSync(path.join(packageRoot, 'LICENSE'), 'utf8');
const lines = [`/*! Generated by packages/plugin-workbench/generate-icons.mjs from @lucide/vue ${metadata.version}.
 * https://github.com/lucide-icons/lucide — no manually maintained SVG paths.
 * Upstream license (including Feather-derived icon notices):
${license.split(/\r?\n/).map(line => ` * ${line}`).join('\n')}
 */`];
for (const [name, upstream] of Object.entries(icons)) {
    const { __iconData } = await import(pathToFileURL(path.join(packageRoot, 'dist/esm/icons', `${upstream}.mjs`)).href);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${__iconData.node.map(node).join('')}</svg>`;
    lines.push(`.plugin-surface [data-presentation-icon="${name}"]{--presentation-icon:url("data:image/svg+xml,${encodeURIComponent(svg)}")}`);
}
const output = fileURLToPath(new URL('./src/lucide-icons.generated.css', import.meta.url));
writeFileSync(output, `${lines.join('\n')}\n`);
writeFileSync(new URL('./src/lucide-license.generated.json', import.meta.url), `${JSON.stringify({
    package: '@lucide/vue', version: metadata.version, source: 'https://github.com/lucide-icons/lucide', license,
}, null, 2)}\n`);
console.log(`Generated ${Object.keys(icons).length} Lucide masks from locked ${metadata.version}.`);

