import { flushPromises, mount } from '@vue/test-utils';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { invoke } from '@tauri-apps/api/core';
import App from './App.vue';
import TasksPage from './TasksPage.vue';
import CfPackInstallPage from './CfPackInstallPage.vue';
import MarketPage from './MarketPage.vue';
import LibraryHome from './LibraryHome.vue';
import { setLocale } from './i18n';
import type { CurseForgePackPreview } from './curseforge';
import type { TaskSnapshot } from './tasks';
vi.mock('@tauri-apps/api/core', () => ({invoke: vi.fn(), isTauri: () => true}));
vi.mock('@tauri-apps/api/event', () => ({listen: vi.fn().mockResolvedValue(() => {})}));
vi.mock('@tauri-apps/api/window', () => ({getCurrentWindow: () => ({isMaximized: vi.fn().mockResolvedValue(false), onCloseRequested: vi.fn().mockResolvedValue(() => {})})}));
vi.mock('./theme', () => ({readTheme: () => 'light', applyTheme: vi.fn()}));
const preview: CurseForgePackPreview = {preview_id: 'recovered-pack', name: 'Recovered adventure', version_id: '1', minecraft_version: '1.21.1', loader_kind: null, loader_version: null, required_files: 0, optional_files: [], selected_optional_files: [], overrides: 1, plan_id: null, files: [], missing: [], ready: false};
const task: TaskSnapshot = {id: 'recovered-task', game_id: null, game_name: preview.name, title: preview.name, kind: 'curseforge_pack_download', state: 'succeeded', progress: null, error: null, can_retry: false, created_at: 1, updated_at: 2, has_result: true};
const stubs = {LibraryHome: true, AppNavigation: true, ProfileSwitcher: true, MarketPage: true, CreateGamePage: true, ImportPackPage: true, ImportLauncherPage: true, SettingsPage: true, ToolsPage: true, PluginsPanel: true, ExtensionSettingsPanel: true, GameDetailsPage: true, GameActionsPage: true, MeshPage: true, ProfilesPage: true, AddProfilePage: true};
beforeEach(() => {
  setLocale('en-US'); vi.mocked(invoke).mockReset(); window.scrollTo = vi.fn();
  vi.mocked(invoke).mockImplementation(async command => {
    if (command === 'list_games') return [];
    if (command === 'list_tasks') return [task];
    if (command === 'list_player_profiles') return {profiles: [], active_id: null};
    if (command === 'get_task_curseforge_pack_preview') return {...preview};
    if (command === 'get_download_settings') return {source: 'official', mirror: ''};
    if (command === 'take_pending_schematic') return null;
    return [];
  });
});
afterEach(() => setLocale('zh-CN'));
it('returns from a recovered CurseForge task to a visible Market on a fresh startup', async () => {
  const wrapper = mount(App, {global: {stubs}}); await flushPromises();
  expect(wrapper.findComponent(MarketPage).exists()).toBe(false);
  await wrapper.get('.tasks-button').trigger('click');
  await wrapper.findComponent(TasksPage).get('.task-actions button').trigger('click'); await flushPromises();
  expect(wrapper.findComponent(CfPackInstallPage).props('initialPreview')).toEqual(preview);
  await wrapper.get('.app-workspace .back-button').trigger('click'); await flushPromises();
  expect(wrapper.findComponent(MarketPage).isVisible()).toBe(true);
  wrapper.unmount();
});
it('resumes, prepares, and creates through CF commands while preventing another task from replacing an active preview', async () => {
  let finishPrepare!: (value: CurseForgePackPreview) => void;
  const preparing = new Promise<CurseForgePackPreview>(resolve => {finishPrepare = resolve;});
  const base = vi.mocked(invoke).getMockImplementation()!;
  const created = {id: 'created', name: preview.name, version: '1.21.1', status: 'installing', directory: 'private', error: null, progress: null};
  vi.mocked(invoke).mockImplementation(async (command, args, options) => command === 'prepare_curseforge_pack' ? preparing : command === 'create_curseforge_pack_game' ? created : base(command, args, options));
  const wrapper = mount(App, {global: {stubs}}); await flushPromises();
  await wrapper.get('.tasks-button').trigger('click'); await wrapper.findComponent(TasksPage).get('.task-actions button').trigger('click'); await flushPromises();
  const page = wrapper.findComponent(CfPackInstallPage);
  await page.get('.primary-button').trigger('click'); await flushPromises();
  expect(invoke).toHaveBeenCalledWith('prepare_curseforge_pack', {previewId: 'recovered-pack', optionalFiles: []});
  await wrapper.get('.tasks-button').trigger('click');
  const continueButton = wrapper.findComponent(TasksPage).get('.task-actions button');
  expect(continueButton.attributes('disabled')).toBeDefined(); await continueButton.trigger('click');
  expect(vi.mocked(invoke).mock.calls.filter(([command]) => command === 'get_task_curseforge_pack_preview')).toHaveLength(1);
  await wrapper.get('.tasks-workspace .back-button').trigger('click');
  finishPrepare({...preview, plan_id: 'recovered-plan', ready: true}); await flushPromises();
  await page.get('.primary-button').trigger('click'); await flushPromises();
  await page.get('form').trigger('submit'); await flushPromises();
  expect(invoke).toHaveBeenCalledWith('create_curseforge_pack_game', {name: preview.name, previewId: preview.preview_id, planId: 'recovered-plan', source: {source: 'official', mirror: ''}, useDefaultDirectory: true});
  expect(wrapper.findComponent(LibraryHome).props('games')).toEqual([created]);
  expect(vi.mocked(invoke).mock.calls.some(([command]) => ['get_task_pack_preview', 'create_mrpack_game'].includes(command))).toBe(false);
  wrapper.unmount();
});
it('reopens the same task into preparation instead of keeping an obsolete ready plan', async () => {
  const base = vi.mocked(invoke).getMockImplementation()!;
  vi.mocked(invoke).mockImplementation(async (command, args, options) => command === 'prepare_curseforge_pack' ? {...preview, plan_id: 'old-plan', ready: true} : base(command, args, options));
  const wrapper = mount(App, {global: {stubs}}); await flushPromises();
  await wrapper.get('.tasks-button').trigger('click'); await wrapper.findComponent(TasksPage).get('.task-actions button').trigger('click'); await flushPromises();
  const page = wrapper.findComponent(CfPackInstallPage);
  await page.get('.primary-button').trigger('click'); await flushPromises();
  await page.get('.primary-button').trigger('click'); await flushPromises(); expect(page.find('form').exists()).toBe(true);
  await wrapper.get('.tasks-button').trigger('click'); await wrapper.findComponent(TasksPage).get('.task-actions button').trigger('click'); await flushPromises();
  expect(wrapper.findComponent(CfPackInstallPage).vm.$.uid).toBe(page.vm.$.uid);
  expect(page.find('form').exists()).toBe(false);
  expect(page.get('.primary-button').text()).toBe('Prepare installation');
  expect(vi.mocked(invoke).mock.calls.some(([command]) => command === 'create_curseforge_pack_game')).toBe(false); wrapper.unmount();
});
it('defers a replacement preview until an in-flight create operation finishes', async () => {
  let finish!: (value: unknown) => void;
  const creating = new Promise(resolve => {finish = resolve;});
  const base = vi.mocked(invoke).getMockImplementation()!;
  vi.mocked(invoke).mockImplementation(async (command, args, options) => command === 'create_curseforge_pack_game' ? creating : base(command, args, options));
  const wrapper = mount(CfPackInstallPage, {props: {initialPreview: {...preview, plan_id: 'active-plan', ready: true}}}); await flushPromises();
  await wrapper.get('form').trigger('submit'); await flushPromises();
  await wrapper.setProps({initialPreview: {...preview, name: 'Replacement'}});
  expect(wrapper.get('#cf-game-name').element).toHaveProperty('value', preview.name);
  expect(wrapper.find('form').exists()).toBe(true);
  finish({id: 'new', status: 'installing'}); await flushPromises();
  expect(wrapper.find('form').exists()).toBe(false);
  expect(wrapper.text()).toContain('Replacement'); wrapper.unmount();
});
it('keeps the task workspace open until its recovered preview has finished loading', async () => {
  let finish!: (value: CurseForgePackPreview) => void;
  const reading = new Promise<CurseForgePackPreview>(resolve => {finish = resolve;});
  const base = vi.mocked(invoke).getMockImplementation()!;
  vi.mocked(invoke).mockImplementation(async (command, args, options) => command === 'get_task_curseforge_pack_preview' ? reading : base(command, args, options));
  const wrapper = mount(App, {global: {stubs}}); await flushPromises();
  await wrapper.get('.tasks-button').trigger('click'); await wrapper.findComponent(TasksPage).get('.task-actions button').trigger('click'); await flushPromises();
  expect(wrapper.get('.tasks-button').attributes('disabled')).toBeDefined();
  const back = wrapper.get('.tasks-workspace .back-button'); expect(back.attributes('disabled')).toBeDefined(); await back.trigger('click');
  expect(wrapper.findComponent(CfPackInstallPage).exists()).toBe(false);
  finish({...preview}); await flushPromises();
  expect(wrapper.findComponent(CfPackInstallPage).exists()).toBe(true);
  expect(wrapper.get('.tasks-button').attributes('disabled')).toBeUndefined(); wrapper.unmount();
});
